const select = document.querySelector("#language-select");
const menuToggle = document.querySelector("#menu-toggle");
const nav = document.querySelector("#nav");

function setLanguage(language) {
  const dictionary = translations[language] || translations.pt;
  const languageCodes = {
    pt: "pt-BR", en: "en", es: "es", fr: "fr",
    de: "de", it: "it", ru: "ru", cy: "cy"
  };

  document.documentElement.lang = languageCodes[language] || "pt-BR";

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.textContent = dictionary[key];
    }
  });

  document.title = "F92D — Linux for everyone.";
  try { localStorage.setItem("f92d-language", language); } catch (_) {}
}

if (select) {
  select.addEventListener("change", event => setLanguage(event.target.value));
  try {
    const saved = localStorage.getItem("f92d-language");
    if (saved && translations[saved]) select.value = saved;
  } catch (_) {}
  setLanguage(select.value || "pt");
}

if (menuToggle && nav) {
  menuToggle.addEventListener("click", () => {
    const isOpen = nav.classList.toggle("open");
    menuToggle.setAttribute("aria-expanded", String(isOpen));
    menuToggle.setAttribute("aria-label", isOpen ? "Fechar menu" : "Abrir menu");
  });

  nav.querySelectorAll("a").forEach(link => {
    link.addEventListener("click", () => {
      nav.classList.remove("open");
      menuToggle.setAttribute("aria-expanded", "false");
      menuToggle.setAttribute("aria-label", "Abrir menu");
    });
  });
}

/* Barrinha neon: acompanha a seção visível na ordem real do HTML. */
const navLinks = [...document.querySelectorAll("#nav a[href^='#']")];
const navTargets = navLinks
  .map(link => document.querySelector(link.getAttribute("href")))
  .filter(Boolean)
  .sort((a, b) => a.offsetTop - b.offsetTop);

function updateActiveLink() {
  if (!navLinks.length || !navTargets.length) return;

  const scrollY = window.scrollY;
  const atBottom = window.innerHeight + scrollY >= document.documentElement.scrollHeight - 4;
  const marker = scrollY + Math.min(150, Math.max(95, window.innerHeight * 0.2));
  let activeId = navTargets[0].id;

  if (atBottom) {
    activeId = navTargets[navTargets.length - 1].id;
  } else {
    for (const section of navTargets) {
      if (section.getBoundingClientRect().top + scrollY <= marker) activeId = section.id;
      else break;
    }
  }

  navLinks.forEach(link => {
    const active = link.hash === `#${activeId}`;
    link.classList.toggle("active", active);
    if (active) link.setAttribute("aria-current", "location");
    else link.removeAttribute("aria-current");
  });
}

navLinks.forEach(link => {
  link.addEventListener("click", () => {
    const target = document.querySelector(link.getAttribute("href"));
    if (target) {
      navLinks.forEach(item => {
        const active = item === link;
        item.classList.toggle("active", active);
        if (active) item.setAttribute("aria-current", "location");
        else item.removeAttribute("aria-current");
      });
    }
    window.setTimeout(updateActiveLink, 400);
  });
});

window.addEventListener("scroll", updateActiveLink, { passive: true });
window.addEventListener("resize", updateActiveLink);
window.addEventListener("load", updateActiveLink);
updateActiveLink();

/* Animações de entrada e revelação ao rolar, sem esconder conteúdo se não houver suporte. */
const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
if (!reduceMotion) {
  document.body.classList.add("motion-enabled");
  const revealItems = document.querySelectorAll(".feature, .notice, .downloads");

  if ("IntersectionObserver" in window) {
    revealItems.forEach(item => item.classList.add("reveal-on-scroll"));
    const revealObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.12, rootMargin: "0px 0px -35px 0px" });
    revealItems.forEach(item => revealObserver.observe(item));
  }
}
